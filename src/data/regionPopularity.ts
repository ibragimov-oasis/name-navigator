export function getRegionData(region: string, year: number): RegionPopularityEntry[] {
  // Найти точное совпадение
  const exact = regionPopularity.find((r) => r.region === region && r.year === year);
  if (exact) return exact.names;
  // Фолбэк: ближайший год для региона
  const sameRegion = regionPopularity
    .filter((r) => r.region === region)
    .sort((a, b) => Math.abs(a.year - year) - Math.abs(b.year - year));
  return sameRegion[0]?.names ?? [];
}
